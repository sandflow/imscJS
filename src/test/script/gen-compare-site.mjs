/* Runs in the browser */
function pageScript() {
    /* global imsc, TESTS, W, H */

    function el(tag, attrs, ...children) {
        const e = document.createElement(tag);
        for (const [k, v] of Object.entries(attrs || {})) e.setAttribute(k, v);
        for (const c of children) e.append(c);
        return e;
    }

    function missing(what) {
        return el("div", { class: "missing" }, what);
    }

    function refImg(t, offset, cls) {
        return el("img", { src: t.refDir + offset + ".png", width: W, height: H, alt: "reference", class: cls });
    }

    function figure(caption, ...content) {
        return el("figure", {}, el("div", { class: "frame" }, ...content), el("figcaption", {}, caption));
    }

    function errorHandler(name) {
        const log = (level) => (msg) => {
            console.log(name + ": " + level + ": " + msg);
            return false;
        };
        return { info: log("info"), warn: log("warn"), error: log("error"), fatal: log("fatal") };
    }

    /* Renders the event at offset of test t into div */
    function render(t, doc, offset, div) {
        try {
            const isd = imsc.generateISD(doc, parseFloat(offset), errorHandler(t.name));
            const imgr = (uri) => t.ttmlDir + uri;
            imsc.renderHTML(isd, div, imgr, H, W, t.params.displayForcedOnlyMode === true, errorHandler(t.name));
        } catch (e) {
            div.replaceWith(missing("imscJS error:\n" + e));
        }
    }

    const nav = document.getElementById("tests");
    const main = document.getElementById("test");

    const links = new Map();

    for (const t of TESTS) {
        const a = el("a", { href: "#" + encodeURIComponent(t.name), "data-name": t.name.toLowerCase() }, t.name);
        links.set(t.name, a);
        nav.append(el("li", {}, a));
    }

    /* Parses the selected test and renders all its events */
    function showTest(t) {
        for (const a of links.values()) a.removeAttribute("aria-current");

        main.replaceChildren();

        if (!t) {
            main.append(el("p", { class: "muted" }, "Select a test."));
            return;
        }

        const link = links.get(t.name);
        link.setAttribute("aria-current", "page");
        link.scrollIntoView({ block: "nearest" });

        document.title = t.name + " - " + document.body.dataset.suite;

        main.append(
            el("h2", {}, t.name),
            el("div", { class: "muted" }, el("a", { href: t.ttmlDir + t.path.split("/").pop() }, t.path)));

        let doc = null;
        let renderedEvents = [];

        try {
            doc = imsc.fromXML(t.ttml.replace(/\r\n/g, "\n"), errorHandler(t.name));
            renderedEvents = doc.getMediaTimeEvents().map((o) => o.toFixed(6));
        } catch (e) {
            main.append(missing("imscJS error:\n" + e));
        }

        const offsets = [...new Set([...renderedEvents, ...t.refEvents])].sort((a, b) => parseFloat(a) - parseFloat(b));

        for (const offset of offsets) {
            const hasRef = t.refEvents.includes(offset);
            const hasRender = renderedEvents.includes(offset);

            let renderFigure;

            if (hasRender) {
                const div = el("div", { class: "render" });
                const frame = el("div", { class: "frame" }, div);
                if (hasRef) frame.append(refImg(t, offset, "over"));
                renderFigure = el("figure", {}, frame, el("figcaption", {}, "imscJS" + (hasRef ? " (reference overlaid)" : "")));
                /* rendered once attached, since imscJS measures the layout */
                renderFigure.renderEvent = () => render(t, doc, offset, div);
            } else {
                renderFigure = figure("imscJS", missing("no imscJS event at this offset"));
            }

            main.append(el("div", { class: "event" },
                el("h3", {}, offset + " s"),
                el("div", { class: "row" },
                    hasRef
                        ? figure(el("a", { href: t.refDir + offset + ".png" }, "reference PNG"), refImg(t, offset, ""))
                        : figure("reference PNG", missing("reference PNG missing")),
                    renderFigure)));

            if (renderFigure.renderEvent) renderFigure.renderEvent();
        }

        applyMode();
    }

    function selectedTest() {
        const name = decodeURIComponent(location.hash.slice(1));
        return TESTS.find((t) => t.name === name);
    }

    const filter = document.getElementById("filter");
    const mode = document.getElementById("mode");
    const opacity = document.getElementById("opacity");
    const count = document.getElementById("count");

    function applyFilter() {
        const q = filter.value.trim().toLowerCase();
        let n = 0;
        for (const a of links.values()) {
            const show = a.dataset.name.includes(q);
            a.parentElement.hidden = !show;
            if (show) n++;
        }
        count.textContent = n + " / " + TESTS.length + " tests";
    }

    function applyMode() {
        document.body.classList.toggle("blend-difference", mode.value === "difference");
        document.body.classList.toggle("hide-overlay", mode.value === "none");
        document.getElementById("opacity-label").hidden = mode.value !== "opacity";
        for (const img of document.querySelectorAll("img.over")) img.style.opacity = opacity.value;
    }

    /* Up/down arrow keys move to the previous/next visible test */
    function step(dir) {
        const visible = [...links.values()].filter((a) => !a.parentElement.hidden);
        const current = selectedTest();
        const i = current ? visible.indexOf(links.get(current.name)) : -1;
        const next = visible[i < 0 ? 0 : i + dir];
        if (next) location.hash = next.getAttribute("href");
    }

    document.addEventListener("keydown", (e) => {
        if (e.target instanceof HTMLInputElement || e.target instanceof HTMLSelectElement) return;
        if (e.key === "ArrowDown" || e.key === "j") { step(1); e.preventDefault(); }
        if (e.key === "ArrowUp" || e.key === "k") { step(-1); e.preventDefault(); }
    });

    filter.addEventListener("input", applyFilter);
    mode.addEventListener("change", applyMode);
    opacity.addEventListener("input", applyMode);
    window.addEventListener("hashchange", () => showTest(selectedTest()));

    applyFilter();
    showTest(selectedTest() || null);
}

