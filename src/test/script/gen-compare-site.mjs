/*
 * Generates a static website that compares the HTML renders generated by
 * imscJS for the imsc-tests test suites with the reference PNGs included in
 * imsc-tests.
 *
 * imscJS renders the events of a test live, when the test is selected, in the
 * browser viewing the site, so that layout-dependent values (e.g. fillLineGap
 * paddings) are computed using that browser's fonts. The reference PNG is shown next to the render and can be
 * overlaid on top of it, either blended in difference mode or with adjustable
 * opacity.
 *
 * TTML documents are embedded in the pages, since browsers do not allow
 * fetch() from file:// pages, and the site can therefore be opened directly
 * from disk.
 *
 * Requires dist/imsc.debug.js (npm run build).
 *
 * Usage:
 *   node src/test/script/gen-compare-site.mjs [imsc-tests/imsc1 imsc-tests/imsc1_1 ...] [--out=build/compare]
 *
 * Open <out>/index.html in a browser.
 */

import fs from "node:fs";
import path from "node:path";
import { RESOURCES_DIR, IMSC_BUNDLE_PATH } from "./render-harness.mjs";

const DEFAULT_REFFILES_ROOTS = ["imsc-tests/imsc1", "imsc-tests/imsc1_1", "imsc-tests/imsc1_2", "imsc-tests/imsc1_3"];

/* Must match the dimensions of the reference PNGs */
const RENDER_WIDTH = 640;
const RENDER_HEIGHT = 360;

function escapeHTML(s) {
    return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}

/* JSON that can be safely embedded in a <script> element */
function scriptJSON(v) {
    return JSON.stringify(v).replace(/</g, "\\u003c");
}

function writeFile(filePath, contents) {
    fs.mkdirSync(path.dirname(filePath), { recursive: true });
    fs.writeFileSync(filePath, contents);
}

